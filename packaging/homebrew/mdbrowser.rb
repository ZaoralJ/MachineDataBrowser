      sha256 "REPLACE_WITH_OSX_ARM64_SHA256"
    end
    on_intel do
      url "https://github.com/ZaoralJ/MachineDataBrowser/releases/download/v#{version}/mdbrowser-#{version}-osx-x64.tar.gz"
      sha256 "REPLACE_WITH_OSX_X64_SHA256"
